  install();
  renderPage();

  // `accretion-core-governance` is seeded into the registry and installed nowhere.
  const governance = within(await screen.findByRole("row", { name: "accretion-core-governance" }));
  expect(governance.getByText("NOT_INSTALLED")).toBeInTheDocument();
  expect(governance.getByText("none requested")).toBeInTheDocument();
