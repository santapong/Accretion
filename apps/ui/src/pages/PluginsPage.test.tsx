test("inspecting a plugin reads its detail for the workspace it is installed in", async () => {
  const calls = install();
  renderPage();

  fireEvent.click(await screen.findByRole("button", { name: `Inspect ${RESEARCH}` }));

  await waitFor(() =>
    expect(calls).toContainEqual({
      url: `/api/v1/plugins/${RESEARCH}?workspace_id=${WORKSPACE}`,
      method: "GET",
    }),
  );
  // A workspace-blind read would answer with no installation at all, so the query
  // string is load-bearing rather than decorative.
  expect(calls.map((call) => call.url)).not.toContain(`/api/v1/plugins/${RESEARCH}`);
});

test("the detail panel shows the version, state, grants, connector status, and lifecycle history", async () => {
  install();
  renderPage();

  fireEvent.click(await screen.findByRole("button", { name: `Inspect ${RESEARCH}` }));

  const panel = within(await screen.findByRole("region", { name: `Plugin detail ${RESEARCH}` }));
  expect(panel.getByLabelText("Installation summary")).toHaveTextContent(
    "version 1.0.0 · state ENABLED · trust BUILTIN",
  );

  const requested = within(panel.getByLabelText("Requested capabilities"));
  expect(requested.getByText("research.literature.search")).toBeInTheDocument();
  expect(requested.getByText("github.search")).toBeInTheDocument();

  const grant = within(panel.getByLabelText("grant github.search"));
  expect(grant.getByText("GRANTED · requested github.read · granted github.read")).toBeInTheDocument();

  // Connector status is the diagnosis AC3-UI-01 asks for: optional-and-unsatisfied is
  // not the same fault as required-and-unsatisfied.
  const connector = within(panel.getByLabelText("connector research-openalex"));
  expect(connector.getByText("not satisfied — optional")).toBeInTheDocument();

  const events = within(panel.getByLabelText("Recent events"));
  expect(events.getByText("ENABLED · READY → ENABLED")).toBeInTheDocument();
  expect(events.getByText("INSTALL_VALIDATING · DISCOVERED → VALIDATING")).toBeInTheDocument();
});

test("connector status distinguishes satisfied, optional, and required-and-missing", () => {
  const base: PluginConnectorResolution = {
    connector_id: "research-openalex",
    required: false,
    satisfied: false,
    connection_id: null,
    missing_scopes: [],
  };
  expect(resolutionText(base)).toBe("not satisfied — optional");
  expect(resolutionText({ ...base, required: true })).toBe("not satisfied — required");
  expect(
    resolutionText({ ...base, required: true, missing_scopes: ["research.read"] }),
  ).toBe("not satisfied — required · missing scopes research.read");
  expect(resolutionText({ ...base, satisfied: true, connection_id: "conn_1" })).toBe(
    "satisfied by conn_1",
  );
});

test("the join keeps the installation's version and state, not the registry's", () => {
  const rows = new Map(pluginRows(PLUGINS, INSTALLATIONS).map((row) => [row.plugin_id, row]));
  const research = rows.get(RESEARCH);
  const registry = PLUGINS.find((entry) => entry.plugin_id === RESEARCH);
  const installation = INSTALLATIONS.find((item) => item.plugin_id === RESEARCH);
  expect(research?.state).toBe(installation?.state);
  expect(research?.version).toBe(installation?.version);
  expect(research?.registry).toBe(registry);
  expect(rows.get("accretion-core-governance")?.installation).toBeNull();
});

test("the listing is a focusable scroll region so it can be reached without a mouse", async () => {
  install();
  renderPage();

  const region = await screen.findByRole("region", { name: "Installed plugins" });
  // 0, not -1. This test is named for reaching the region WITHOUT A MOUSE, and -1 is
  // exactly what prevents that: it makes an element focusable only from script, and
  // removes it from the tab order. The assertion contradicted the test's own name until
  // axe-core 4.13's `scrollable-region-focusable` rule reported it on five routes -
  // `.registry-card` scrolls horizontally at narrow widths, so a keyboard user could see
  // the region and never reach its clipped content.
  expect(region).toHaveAttribute("tabindex", "0");
  region.focus();
  expect(document.activeElement).toBe(region);
});

test("the detail panel shows the manifest's skills, scopes, verifiers, policies and projections", async () => {
  install();
  renderPage();

  fireEvent.click(await screen.findByRole("button", { name: `Inspect ${RESEARCH}` }));
  const panel = within(await screen.findByRole("region", { name: `Plugin detail ${RESEARCH}` }));

  // SDD 16.1 lists all five on the detail screen. They live on the version record's
  // manifest, so a panel reading only the installation cannot show them.
  const skills = within(panel.getByLabelText("Skills"));
  expect(
    skills.getByLabelText("skill accretion-research-literature-review"),
  ).toBeInTheDocument();
  expect(skills.queryByLabelText("skill accretion-sample-echo")).toBeNull();

  const scopes = within(panel.getByLabelText("Required scopes"));
  expect(scopes.getByLabelText("scopes research-openalex")).toHaveTextContent(
    "optional · no scopes requested",
  );

  expect(within(panel.getByLabelText("Policies")).getByText("local-capability-policy"))
    .toBeInTheDocument();
  // The research manifest declares no verifiers and no projections, and an empty
  // section has to read as "none declared" rather than as a missing screen.
  expect(within(panel.getByLabelText("Verifiers")).getByText("This plugin declares no verifiers."))
    .toBeInTheDocument();
  expect(
    within(panel.getByLabelText("Provider projections")).getByText(
      "This plugin ships no provider projections.",
    ),
  ).toBeInTheDocument();
});

test("a required connector's scopes read differently from an optional connector's silence", () => {
  const manifest = DETAIL.version_record!.manifest;
  const withRequired = {
    ...manifest,
    required_connectors: [
      { connector_id: "github", scopes: ["repo:read", "issues:read"], reason: "" },
    ],
  };
  const requirements = scopeRequirements(withRequired);
  const optional = scopeRequirements(manifest);

  expect(requirements[0]).toEqual({
    connector_id: "github",
    required: true,
    scopes: ["repo:read", "issues:read"],
  });
  expect(scopeText(requirements[0])).toBe("required · scopes repo:read issues:read");
  expect(scopeText(optional[0])).toBe("optional · no scopes requested");
  expect(scopeText(requirements[0])).not.toBe(scopeText(optional[0]));
  expect(scopeRequirements(null)).toEqual([]);
});

test("provider projections are listed as provider-to-path pairs in a stable order", () => {
  const manifest = DETAIL.version_record!.manifest;
  expect(providerProjections(manifest)).toEqual([]);
  expect(
    providerProjections({
      ...manifest,
      provider_projections: { openai: "projections/openai.json", anthropic: "projections/a.json" },
    }),
  ).toEqual([
    ["anthropic", "projections/a.json"],
    ["openai", "projections/openai.json"],
  ]);
});
