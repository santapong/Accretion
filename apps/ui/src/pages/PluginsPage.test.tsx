import { cleanup, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { afterEach, beforeEach, expect, test, vi } from "vitest";
import { PluginsPage } from "./PluginsPage";
import { pluginRows, providerProjections, resolutionText, scopeRequirements, scopeText } from "./pluginRows";
import type { components } from "../api/schema";
import pluginsFixture from "./__fixtures__/plugins.json";
import installationsFixture from "./__fixtures__/plugin-installations.json";
import detailFixture from "./__fixtures__/plugin-detail.json";

type MetaPlugin = components["schemas"]["MetaPlugin"];
type PluginInstallation = components["schemas"]["PluginInstallation"];
type PluginDetail = components["schemas"]["PluginDetail"];
type PluginConnectorResolution = components["schemas"]["PluginConnectorResolution"];

// Generated by tests/test_v03_m6_admin_surface.py from the live API and byte-compared
// there, so these are what /api/v1/plugins really answers rather than a guess. Typed
// against the generated schema, so a contract change breaks `npm run check` too.
const PLUGINS = pluginsFixture as MetaPlugin[];
const INSTALLATIONS = installationsFixture as PluginInstallation[];
const DETAIL = detailFixture as PluginDetail;

const RESEARCH = "accretion-research";
const SAMPLE = "accretion-sample-plugin";
const WORKSPACE = "wks_m6_01";

interface Call {
  url: string;
  method: string;
}

function install(): Call[] {
  const calls: Call[] = [];
  vi.mocked(fetch).mockImplementation(async (input, init) => {
    const url = String(input);
    calls.push({ url, method: init?.method ?? "GET" });
    const body = url.includes("/api/v1/plugins/installations")
      ? INSTALLATIONS
      : url.includes(`/api/v1/plugins/${RESEARCH}`)
        ? DETAIL
        : url.includes(`/api/v1/plugins/${SAMPLE}`)
          ? { ...DETAIL, plugin_id: SAMPLE, installation: null, recent_events: [] }
          : PLUGINS;
    return { ok: true, status: 200, json: async () => body } as Response;
  });
  return calls;
}

function renderPage() {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  return render(
    <QueryClientProvider client={client}>
      <MemoryRouter initialEntries={["/admin/plugins"]}>
        <Routes><Route path="/admin/plugins" element={<PluginsPage />} /></Routes>
      </MemoryRouter>
    </QueryClientProvider>,
  );
}

vi.stubGlobal("fetch", vi.fn());

beforeEach(() => {
  vi.mocked(fetch).mockReset();
});

afterEach(() => {
  cleanup();
  vi.clearAllMocks();
});

test("the page is headed Plugins and its two rows disagree on state, trust, and requested capabilities", async () => {
  install();
  renderPage();

  expect(screen.getByRole("heading", { level: 1, name: "Plugins" })).toBeInTheDocument();

  const research = within(await screen.findByRole("row", { name: RESEARCH }));
  expect(research.getByText("ENABLED")).toBeInTheDocument();
  expect(research.getByText("1.0.0")).toBeInTheDocument();
  expect(
    research.getByText(
      "research.literature.search · research.paper.fetch · research.metadata.resolve · research.citation.verify · github.search",
    ),
  ).toBeInTheDocument();

  // The differential: the second installed row shares the trust level but agrees on
  // nothing else, so a page that rendered one row's data twice fails here.
  const sample = within(await screen.findByRole("row", { name: SAMPLE }));
  expect(sample.getByText("DISABLED")).toBeInTheDocument();
  expect(sample.getByText("0.1.0")).toBeInTheDocument();
  expect(sample.getByText("accretion.sample.echo · accretion.sample.record")).toBeInTheDocument();
  expect(sample.queryByText("ENABLED")).toBeNull();
  expect(research.queryByText("DISABLED")).toBeNull();
});

